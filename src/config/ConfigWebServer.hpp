#ifndef CONFIG_WEBSERVER_HPP
#define CONFIG_WEBSERVER_HPP

#include <Arduino.h>
#include <ESP8266WebServer.h>
#include <EEPROM.h>
#include <ESP8266WiFi.h>


// ============================================================================
// EEPROM
// ============================================================================

#define EEPROM_SIZE 512

#define CONFIG_MAGIC   0x12345678
#define CONFIG_VERSION 2


// ============================================================================
// WEBSERVER
// ============================================================================

#define WEB_TIMEOUT_MS 120000UL


// ============================================================================
// WLAN
// ============================================================================

#define WIFI_SSID_LENGTH     64
#define WIFI_PASSWORD_LENGTH 64

#define MAX_WIFI_NETWORKS 20


// ============================================================================
// KONFIGURATION
// ============================================================================

struct ConfigData
{
    uint32_t magic;

    uint16_t version;


    // -------------------------------------------------------------------------
    // Uhr
    // -------------------------------------------------------------------------

    uint8_t sleepHour;
    uint8_t sleepMinute;

    uint8_t wakeupHour;
    uint8_t wakeupMinute;


    // -------------------------------------------------------------------------
    // Header
    // -------------------------------------------------------------------------

    bool header1;
    bool header2;


    // -------------------------------------------------------------------------
    // WLAN
    // -------------------------------------------------------------------------

    char wifiSSID[WIFI_SSID_LENGTH];

    char wifiPassword[WIFI_PASSWORD_LENGTH];
};


// ============================================================================
// GEFUNDENES WLAN
// ============================================================================

struct WifiNetwork
{
    String ssid;

    int rssi;

    bool secure;
};


// ============================================================================
// KLASSE
// ============================================================================

class ConfigWebServer
{
public:

    ConfigWebServer();


    // -------------------------------------------------------------------------
    // Konfiguration laden
    // -------------------------------------------------------------------------

    void begin();


    // -------------------------------------------------------------------------
    // Eigenen Access Point + Webserver starten
    // -------------------------------------------------------------------------

    void start();


    // -------------------------------------------------------------------------
    // Webserver bearbeiten
    // -------------------------------------------------------------------------

    void handle();


    // -------------------------------------------------------------------------
    // Stoppen
    // -------------------------------------------------------------------------

    void stop();


    bool isActive();


    // -------------------------------------------------------------------------
    // Konfiguration geändert
    // -------------------------------------------------------------------------

    bool hasConfigChanged() const;

    void clearConfigChanged();


    // -------------------------------------------------------------------------
    // Sleep
    // -------------------------------------------------------------------------

    uint8_t getSleepHour() const;

    uint8_t getSleepMinute() const;


    // -------------------------------------------------------------------------
    // Wakeup
    // -------------------------------------------------------------------------

    uint8_t getWakeupHour() const;

    uint8_t getWakeupMinute() const;


    // -------------------------------------------------------------------------
    // Header
    // -------------------------------------------------------------------------

    bool getHeader1() const;

    bool getHeader2() const;


    // -------------------------------------------------------------------------
    // WLAN
    // -------------------------------------------------------------------------

    String getWifiSSID() const;

    String getWifiPassword() const;


    // -------------------------------------------------------------------------
    // WLAN-Zugangsdaten setzen
    // -------------------------------------------------------------------------

    void setWifiCredentials(
        const String& ssid,
        const String& password
    );


    // -------------------------------------------------------------------------
    // WLAN automatisch scannen
    // -------------------------------------------------------------------------

    void scanWifi();


private:

    // -------------------------------------------------------------------------
    // HTTP Handler
    // -------------------------------------------------------------------------

    void handleRoot();

    void handleSave();

    void handleWifi();

    void handleClose();


    // -------------------------------------------------------------------------
    // Konfiguration
    // -------------------------------------------------------------------------

    void load();

    void save();


    // -------------------------------------------------------------------------
    // HTML
    // -------------------------------------------------------------------------

    String htmlPage(
        bool saved
    );


    // -------------------------------------------------------------------------
    // WLAN
    // -------------------------------------------------------------------------

    String wifiStatusText();

    String wifiStatusClass();

    String wifiNetworkOptions();


    // -------------------------------------------------------------------------
    // Server
    // -------------------------------------------------------------------------

    ESP8266WebServer server;


    // -------------------------------------------------------------------------
    // Status
    // -------------------------------------------------------------------------

    unsigned long startTime;

    bool active;

    bool configChanged;


    // -------------------------------------------------------------------------
    // Konfiguration
    // -------------------------------------------------------------------------

    ConfigData config;


    // -------------------------------------------------------------------------
    // WLAN Scan
    // -------------------------------------------------------------------------

    WifiNetwork wifiNetworks[MAX_WIFI_NETWORKS];

    int wifiNetworkCount;
};

#endif